#!/usr/bin/env node
/**
 * Regenerates `packages/js/test/state-resolution-cases.json`.
 *
 * The React package shares `states.ts` with the framework-free one as a
 * byte-identical copy, and a test diffs them. The Flutter package cannot do
 * that — `packages/flutter/lib/src/states.dart` is a translation, and nothing
 * can diff Dart against TypeScript. So the two are held together by their
 * *behaviour* instead: this writes out every spelling the JavaScript registry
 * accepts and the id it resolves to, and both sides assert against the result.
 *
 *   packages/js/test/state-resolution.test.ts    fixture still matches the TS registry
 *   packages/flutter/test/state_resolution_test.dart   Dart resolves every case identically
 *
 * Change either registry and one of those fails until the fixture is regenerated
 * and both agree again.
 *
 *     pnpm --filter bharat-choropleth-js build
 *     node scripts/generate-state-resolution-cases.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const { STATES, resolveState } = await import("../packages/js/dist/index.js");

/**
 * Every spelling shape the registry is meant to accept, for every state, plus
 * each alias. Derived from the registry rather than typed out, so a state added
 * there is covered here without anyone remembering to add it.
 */
const spellings = new Set();
for (const state of STATES) {
  spellings.add(state.id);
  spellings.add(state.name);
  spellings.add(state.name.toLowerCase());
  spellings.add(state.name.toUpperCase());
  spellings.add(state.slug);
  spellings.add(state.slug.replace(/-/g, "")); // separator-free: "tamilnadu"
  spellings.add(state.slug.replace(/-/g, "_")); // underscored: "tamil_nadu"
  spellings.add(state.slug.replace(/-/g, " ")); // spaced: "tamil nadu"
}
const source = readFileSync(new URL("../packages/js/src/states.ts", import.meta.url), "utf8");
for (const [, alias] of source.matchAll(/^\s*"?([a-z0-9-]+)"?:\s*"[a-z0-9-]+",/gm)) spellings.add(alias);

const resolves = {};
for (const spelling of [...spellings].sort()) {
  const resolved = resolveState(spelling);
  if (resolved) resolves[spelling] = resolved.id;
}

// Recorded too, so an over-eager matcher on either side is caught as well as a
// missing one: "tamil" must not become Tamil Nadu.
const doesNotResolve = ["", "Xanadu", "Not A State", "goaa", "tamil"].filter((input) => !resolveState(input));

writeFileSync(
  new URL("../packages/js/test/state-resolution-cases.json", import.meta.url),
  `${JSON.stringify(
    {
      note: "Generated by scripts/generate-state-resolution-cases.mjs from packages/js/src/states.ts. packages/flutter/lib/src/states.dart must resolve every one of these identically.",
      states: STATES.length,
      resolves,
      doesNotResolve,
    },
    null,
    2,
  )}\n`,
);

console.log(`state-resolution-cases.json: ${Object.keys(resolves).length} resolving, ${doesNotResolve.length} not.`);
